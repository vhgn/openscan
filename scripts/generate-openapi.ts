/**
 * `npm run generate`: writes public/openapi.json (served at /openapi.json) from
 * the API contract in src/lib/api/contract.ts.
 *
 *   npm run generate              write the spec
 *   npm run generate -- --check   fail if the committed spec is stale (CI; also a unit test)
 *
 * It also fails when a route file under src/routes/api has no entry in
 * API_ROUTES / UNDOCUMENTED_ROUTES, or an entry points at a route that no longer exists.
 */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'
import { z } from 'zod'
import { API_ROUTES, UNDOCUMENTED_ROUTES, type ApiRoute } from '../src/lib/api/contract.ts'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
export const SPEC_PATH = join(root, 'public/openapi.json')
const ROUTES_DIR = join(root, 'src/routes/api')
const ref = (id: string) => `#/components/schemas/${id}`

type Json = Record<string, unknown>

/** JSON Schema for one zod schema: a $ref when it is a named component, inline otherwise. */
function schemaFor(schema: z.ZodType, io: 'input' | 'output'): Json {
  const id = z.globalRegistry.get(schema)?.id
  if (id) return { $ref: ref(id) }
  const { $schema: _s, ...json } = z.toJSONSchema(schema, { io, unrepresentable: 'any' }) as Json
  return json
}

/**
 * Named schemas (`.meta({ id })`). Request bodies, and any schema whose id ends in "Request",
 * are described as input (fields with defaults are optional); the rest as output.
 */
function components(): Record<string, Json> {
  const bodies = API_ROUTES.map((r) => r.body && z.globalRegistry.get(r.body)?.id).filter(Boolean)
  const isRequest = (id: string) => bodies.includes(id) || id.endsWith('Request')
  const convert = (io: 'input' | 'output') =>
    (z.toJSONSchema(z.globalRegistry, { io, uri: ref, unrepresentable: 'any' }) as { schemas: Record<string, Json> }).schemas
  const input = convert('input')
  const output = convert('output')
  return Object.fromEntries(
    Object.keys(output)
      .sort()
      .map((id) => {
        const { $schema: _s, $id: _i, ...json } = (isRequest(id) ? input : output)[id]
        return [id, json]
      }),
  )
}

const SECURITY: Record<ApiRoute['auth'], Json[] | undefined> = {
  session: [{ session: [] }],
  webhook: [{ webhookSignature: [] }],
  agent: [{ agentToken: [] }],
  none: [],
}

function operation(r: ApiRoute): Json {
  const parameters = [
    ...Object.entries(r.pathParams ?? {}).map(([name, description]) => ({ name, in: 'path', required: true, description, schema: { type: 'string' } })),
    ...Object.entries(r.query ?? {}).map(([name, q]) => ({ name, in: 'query', required: Boolean(q.required), description: q.description, schema: { type: 'string' } })),
    ...Object.entries(r.headers ?? {}).map(([name, h]) => ({ name, in: 'header', required: Boolean(h.required), description: h.description, schema: { type: 'string' } })),
  ]
  return {
    operationId: `${r.method}${r.path.replace(/[{}]/g, '').replace(/(^|[/_-])(\w)/g, (_m, _p, c: string) => c.toUpperCase())}`,
    summary: r.summary,
    ...(r.description ? { description: r.description } : {}),
    tags: r.tags,
    security: SECURITY[r.auth],
    ...(parameters.length ? { parameters } : {}),
    ...(r.body ? { requestBody: { required: true, content: { 'application/json': { schema: schemaFor(r.body, 'input') } } } } : {}),
    responses: Object.fromEntries(
      Object.entries(r.responses).map(([status, res]) => [
        status,
        {
          description: res.description,
          ...(res.redirect ? { headers: { Location: { description: 'Redirect target', schema: { type: 'string' } } } } : {}),
          ...(res.schema ? { content: { 'application/json': { schema: schemaFor(res.schema, 'output') } } } : {}),
          ...(res.text ? { content: { 'text/plain': { schema: { type: 'string' } } } } : {}),
        },
      ]),
    ),
  }
}

export function buildSpec(): Json {
  const paths: Record<string, Json> = {}
  for (const r of API_ROUTES) (paths[r.path] ??= {})[r.method] = operation(r)
  return {
    openapi: '3.1.0',
    info: {
      title: 'openscan API',
      version: '1.0.0',
      description:
        'REST API of openscan. Authenticated routes use the `openscan_session` cookie set by "Sign in with GitHub". Generated by `npm run generate` from src/lib/api/contract.ts; do not edit by hand.',
    },
    servers: [{ url: '/', description: 'This deployment' }],
    tags: [
      { name: 'Scans', description: 'Security briefs and repository reads' },
      { name: 'GitHub', description: 'GitHub App integration' },
      { name: 'Auth', description: 'Sign-in and sessions (browser redirects)' },
      { name: 'Agent', description: 'Read-only, plain-text API for Codex Cloud tasks during a scan' },
    ],
    paths,
    components: {
      securitySchemes: {
        session: { type: 'apiKey', in: 'cookie', name: 'openscan_session', description: 'Set by /api/auth/github/callback' },
        webhookSignature: { type: 'apiKey', in: 'header', name: 'X-Hub-Signature-256', description: 'HMAC-SHA256 of the raw body with GITHUB_WEBHOOK_SECRET' },
        agentToken: { type: 'http', scheme: 'bearer', description: 'Short-lived token openscan gives a Codex Cloud task for the duration of its scan' },
      },
      schemas: components(),
    },
  }
}

/** Route ids registered under src/routes/api (from each file's createFileRoute('…')). */
export function apiRouteIds(dir = ROUTES_DIR): Map<string, string> {
  const ids = new Map<string, string>()
  for (const entry of readdirSync(dir, { withFileTypes: true, recursive: true })) {
    if (!entry.isFile() || !/\.tsx?$/.test(entry.name)) continue
    const file = join(entry.parentPath, entry.name)
    const m = /createFileRoute\(\s*['"`]([^'"`]+)['"`]\s*\)/.exec(readFileSync(file, 'utf8'))
    if (m) ids.set(m[1], relative(root, file))
  }
  return ids
}

/** Problems with the registry's coverage of the route files; empty when every route is accounted for. */
export function coverageProblems(): string[] {
  const files = apiRouteIds()
  const documented = new Set([...API_ROUTES.map((r) => r.routeId), ...Object.keys(UNDOCUMENTED_ROUTES)])
  return [
    ...[...files].filter(([id]) => !documented.has(id)).map(([id, file]) => `${file} (${id}) is not in API_ROUTES or UNDOCUMENTED_ROUTES in src/lib/api/contract.ts`),
    ...[...documented].filter((id) => !files.has(id)).map((id) => `src/lib/api/contract.ts lists ${id}, but no file under src/routes/api registers it`),
  ]
}

export const renderSpec = () => `${JSON.stringify(buildSpec(), null, 2)}\n`

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const problems = coverageProblems()
  for (const p of problems) console.error(`✗ ${p}`)
  if (problems.length) process.exit(1)
  const spec = renderSpec()
  const rel = relative(root, SPEC_PATH)
  if (process.argv.includes('--check')) {
    let current = ''
    try {
      current = readFileSync(SPEC_PATH, 'utf8')
    } catch {}
    if (current !== spec) {
      console.error(`✗ ${rel} is out of date. Run: npm run generate`)
      process.exit(1)
    }
    console.log(`✓ ${rel} is up to date`)
  } else {
    writeFileSync(SPEC_PATH, spec)
    console.log(`✓ Wrote ${rel} (${API_ROUTES.length} operations)`)
  }
}
